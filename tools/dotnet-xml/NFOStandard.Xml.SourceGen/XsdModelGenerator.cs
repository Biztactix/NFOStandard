using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Xml;
using System.Xml.Schema;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace NFOStandard.Xml.SourceGen;

[Generator]
public sealed class XsdModelGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(productionContext =>
        {
            var schemaSet = new XmlSchemaSet();
            foreach (var schema in LoadEmbeddedSchemas())
            {
                schemaSet.Add(schema);
            }

            schemaSet.Compile();

            var generator = new ModelGenerator(schemaSet);
            var source = generator.Generate();
            productionContext.AddSource("NfoModels.g.cs", SourceText.From(source, Encoding.UTF8));
        });
    }

    private static IEnumerable<XmlSchema> LoadEmbeddedSchemas()
    {
        var assembly = typeof(XsdModelGenerator).Assembly;
        var resources = assembly.GetManifestResourceNames()
            .Where(name => name.EndsWith(".xsd", StringComparison.OrdinalIgnoreCase))
            .OrderBy(name => name, StringComparer.OrdinalIgnoreCase);

        foreach (var resource in resources)
        {
            using var stream = assembly.GetManifestResourceStream(resource);
            if (stream == null)
            {
                continue;
            }

            using var reader = new StreamReader(stream, Encoding.UTF8);
            var schema = XmlSchema.Read(reader, (_, _) => { });
            if (schema != null)
            {
                yield return schema;
            }
        }
    }

    private sealed class ModelGenerator
    {
        private const string Namespace = "NFOStandard.Xml";
        private readonly XmlSchemaSet _schemaSet;
        private readonly Dictionary<string, string> _nameOverrides = new(StringComparer.OrdinalIgnoreCase)
        {
            ["metadataType"] = "LibraryMetadata",
            ["statsType"] = "Stats",
            ["personType"] = "Person",
            ["ratingType"] = "Rating",
            ["uniqueIdType"] = "UniqueId",
            ["contentRatingType"] = "ContentRating",
            ["mediaFileType"] = "MediaFile",
            ["musicVideoType"] = "MusicVideo",
            ["tvShowType"] = "TvShow",
            ["audiobookType"] = "Audiobook",
            ["adultType"] = "Adult",
            ["animeType"] = "Anime",
            ["videoType"] = "Video",
            ["musicType"] = "Music",
            ["podcastType"] = "Podcast",
            ["albumType"] = "MusicAlbum"
        };
        private readonly Dictionary<XmlSchemaType, string> _typeNames = new();
        private readonly Dictionary<string, GeneratedEnum> _enumNames = new(StringComparer.OrdinalIgnoreCase);
        private readonly HashSet<string> _generated = new(StringComparer.OrdinalIgnoreCase);
        private readonly List<GeneratedType> _types = new();
        private readonly List<GeneratedEnum> _enums = new();

        public ModelGenerator(XmlSchemaSet schemaSet)
        {
            _schemaSet = schemaSet;
        }

        public string Generate()
        {
            var rootElement = FindRootElement();
            if (rootElement != null)
            {
                var rootType = ResolveType(rootElement.ElementSchemaType, "NfoRoot");
                RegisterType(rootType);
            }

            foreach (XmlSchema schema in _schemaSet.Schemas())
            {
                foreach (XmlSchemaType type in schema.SchemaTypes.Values)
                {
                    if (type is XmlSchemaComplexType complexType)
                    {
                        var name = ResolveTypeName(complexType, complexType.Name);
                        if (name != null)
                        {
                            RegisterType(ResolveType(complexType, name));
                        }
                    }
                }
            }

            var builder = new StringBuilder();
            builder.AppendLine("// <auto-generated />");
            builder.AppendLine("#nullable enable");
            builder.AppendLine("#pragma warning disable CS8618");
            builder.AppendLine("using System;");
            builder.AppendLine("using System.Collections.Generic;");
            builder.AppendLine("using System.Xml.Schema;");
            builder.AppendLine("using System.Xml.Serialization;");
            builder.AppendLine();
            builder.AppendLine($"namespace {Namespace};");
            builder.AppendLine();

            foreach (var type in _types.OrderBy(t => t.Name))
            {
                builder.AppendLine(type.ToCode());
            }

            foreach (var enumType in _enums.OrderBy(e => e.Name))
            {
                builder.AppendLine(enumType.ToCode());
            }

            return builder.ToString();
        }

        private XmlSchemaElement? FindRootElement()
        {
            foreach (XmlSchema schema in _schemaSet.Schemas())
            {
                foreach (XmlSchemaElement element in schema.Elements.Values)
                {
                    if (string.Equals(element.Name, "root", StringComparison.OrdinalIgnoreCase))
                    {
                        return element;
                    }
                }
            }

            return null;
        }

        private void RegisterType(GeneratedType type)
        {
            if (_generated.Contains(type.Name))
            {
                return;
            }

            _generated.Add(type.Name);
            _types.Add(type);

            foreach (var nested in type.NestedTypes)
            {
                RegisterType(nested);
            }
        }

        private GeneratedType ResolveType(XmlSchemaType schemaType, string? fallbackName)
        {
            if (_typeNames.TryGetValue(schemaType, out var cachedName))
            {
                return BuildComplexType(schemaType as XmlSchemaComplexType, cachedName);
            }

            var name = ResolveTypeName(schemaType, fallbackName) ?? fallbackName ?? "AnonymousType";
            _typeNames[schemaType] = name;
            return BuildComplexType(schemaType as XmlSchemaComplexType, name);
        }

        private string? ResolveTypeName(XmlSchemaType? schemaType, string? fallbackName)
        {
            var name = schemaType?.Name ?? fallbackName;
            if (string.IsNullOrWhiteSpace(name))
            {
                return null;
            }

            var resolvedName = name ?? string.Empty;
            if (_nameOverrides.TryGetValue(resolvedName, out var overrideName))
            {
                return overrideName;
            }

            var trimmed = resolvedName.EndsWith("Type", StringComparison.OrdinalIgnoreCase)
                ? resolvedName.Substring(0, resolvedName.Length - 4)
                : resolvedName;
            return ToPascal(trimmed);
        }

        private GeneratedType BuildComplexType(XmlSchemaComplexType? complexType, string typeName)
        {
            var type = new GeneratedType(typeName, complexType?.Name, isRoot: string.Equals(typeName, "NfoRoot", StringComparison.OrdinalIgnoreCase));
            if (complexType == null)
            {
                return type;
            }

            if (complexType.ContentModel is XmlSchemaSimpleContent simpleContent)
            {
                type.Properties.Add(new PropertySpec("Value", "string?", "XmlText"));
                if (simpleContent.Content is XmlSchemaSimpleContentExtension extension)
                {
                    foreach (XmlSchemaAttribute attribute in extension.Attributes)
                    {
                        foreach (var property in CreateAttributeProperties(attribute, type.Name))
                        {
                            type.Properties.Add(property);
                        }
                    }
                }

                return type;
            }

            foreach (var property in GetParticleProperties(complexType.ContentTypeParticle, type))
            {
                type.Properties.Add(property);
            }

            foreach (XmlSchemaAttribute attribute in complexType.Attributes)
            {
                foreach (var property in CreateAttributeProperties(attribute, type.Name))
                {
                    type.Properties.Add(property);
                }
            }

            return type;
        }

        private IEnumerable<PropertySpec> GetParticleProperties(XmlSchemaParticle? particle, GeneratedType parent)
        {
            if (particle is XmlSchemaSequence sequence)
            {
                foreach (var item in sequence.Items)
                {
                    foreach (var prop in GetParticleProperties(item as XmlSchemaParticle, parent))
                    {
                        yield return prop;
                    }
                }

                yield break;
            }

            if (particle is XmlSchemaChoice choice)
            {
                foreach (var item in choice.Items)
                {
                    foreach (var prop in GetParticleProperties(item as XmlSchemaParticle, parent))
                    {
                        yield return prop;
                    }
                }

                yield break;
            }

            if (particle is XmlSchemaElement element)
            {
                foreach (var property in CreateElementProperties(element, parent))
                {
                    yield return property;
                }
                yield break;
            }

            yield break;
        }

        private IEnumerable<PropertySpec> CreateElementProperties(XmlSchemaElement element, GeneratedType parent)
        {
            var elementName = element.Name ?? element.RefName.Name ?? "Element";
            var isList = element.MaxOccurs > 1;
            var isOptional = element.MinOccurs == 0;
            var propertyName = ToPascal(elementName);

            string propertyType;
            string? dataType = null;
            GeneratedType? nestedType = null;

            var schemaType = element.ElementSchemaType;
            if (schemaType is XmlSchemaSimpleType simpleType)
            {
                var baseType = MapSimpleType(simpleType, $"{parent.Name}{propertyName}");
                dataType = ResolveXmlDataType(simpleType);
                propertyType = baseType;
            }
            else if (schemaType is XmlSchemaComplexType complexType)
            {
                if (!string.IsNullOrWhiteSpace(complexType.Name))
                {
                    propertyType = ResolveTypeName(complexType, complexType.Name) ?? propertyName;
                }
                else
                {
                    nestedType = ResolveType(complexType, propertyName);
                    propertyType = nestedType.Name;
                }
            }
            else
            {
                propertyType = "string?";
            }

            if (nestedType != null)
            {
                parent.NestedTypes.Add(nestedType);
            }

            if (isOptional && !isList && !IsValueTypeOrEnum(propertyType) && !propertyType.EndsWith("?", StringComparison.OrdinalIgnoreCase))
            {
                propertyType = $"{propertyType}?";
            }

            yield return new PropertySpec(propertyName, propertyType, "XmlElement", elementName, isList, dataType, false);

            if (isOptional && !isList && IsValueTypeOrEnum(propertyType))
            {
                yield return PropertySpec.XmlIgnore($"{propertyName}Specified", "bool");
            }
        }

        private IEnumerable<PropertySpec> CreateAttributeProperties(XmlSchemaAttribute attribute, string parentName)
        {
            var name = attribute.Name ?? attribute.RefName.Name ?? "attribute";
            var propertyName = ToPascal(name);
            var isOptional = attribute.Use != XmlSchemaUse.Required;
            string? dataType = null;
            var type = attribute.AttributeSchemaType is XmlSchemaSimpleType simpleType
                ? MapSimpleType(simpleType, $"{parentName}{propertyName}")
                : "string?";

            if (attribute.AttributeSchemaType is XmlSchemaSimpleType attributeSimpleType)
            {
                dataType = ResolveXmlDataType(attributeSimpleType);
            }

            var properties = new List<PropertySpec>
            {
                new PropertySpec(propertyName, type, "XmlAttribute", name, false, dataType, false)
            };

            if (isOptional && IsValueTypeOrEnum(type))
            {
                properties.Add(PropertySpec.XmlIgnore($"{propertyName}Specified", "bool"));
            }

            return properties;
        }

        private string MapSimpleType(XmlSchemaSimpleType simpleType, string fallbackName)
        {
            if (TryGetEnumValues(simpleType, out var values))
            {
                var enumName = ResolveEnumName(simpleType, fallbackName);
                RegisterEnum(enumName, values);
                return enumName;
            }

            if (simpleType.Datatype == null)
            {
                return "string?";
            }

            var mapped = simpleType.Datatype.TypeCode switch
            {
                XmlTypeCode.Boolean => "bool",
                XmlTypeCode.Decimal => "decimal",
                XmlTypeCode.Integer => "int",
                XmlTypeCode.NonPositiveInteger => "int",
                XmlTypeCode.NegativeInteger => "int",
                XmlTypeCode.Long => "long",
                XmlTypeCode.Int => "int",
                XmlTypeCode.Short => "short",
                XmlTypeCode.Byte => "byte",
                XmlTypeCode.NonNegativeInteger => "int",
                XmlTypeCode.PositiveInteger => "int",
                XmlTypeCode.UnsignedLong => "ulong",
                XmlTypeCode.UnsignedInt => "uint",
                XmlTypeCode.UnsignedShort => "ushort",
                XmlTypeCode.UnsignedByte => "byte",
                XmlTypeCode.Float => "float",
                XmlTypeCode.Double => "double",
                XmlTypeCode.Date => "DateTime",
                XmlTypeCode.DateTime => "DateTime",
                _ => "string?"
            };

            return mapped;
        }

        private bool IsValueTypeOrEnum(string typeName)
        {
            if (typeName.EndsWith("?", StringComparison.OrdinalIgnoreCase))
            {
                typeName = typeName.Substring(0, typeName.Length - 1);
            }

            if (_enumNames.ContainsKey(typeName))
            {
                return true;
            }

            return typeName switch
            {
                "bool" => true,
                "decimal" => true,
                "int" => true,
                "long" => true,
                "short" => true,
                "byte" => true,
                "float" => true,
                "double" => true,
                "DateTime" => true,
                "uint" => true,
                "ushort" => true,
                "ulong" => true,
                _ => false
            };
        }

        private string? ResolveXmlDataType(XmlSchemaSimpleType simpleType)
        {
            if (simpleType.Datatype == null)
            {
                return null;
            }

            return simpleType.Datatype.TypeCode switch
            {
                XmlTypeCode.Date => "date",
                _ => null
            };
        }

        private bool TryGetEnumValues(XmlSchemaSimpleType simpleType, out List<string> values)
        {
            values = new List<string>();
            if (simpleType.Content is not XmlSchemaSimpleTypeRestriction restriction)
            {
                return false;
            }

            foreach (var facet in restriction.Facets)
            {
                if (facet is XmlSchemaEnumerationFacet enumerationFacet && enumerationFacet.Value != null)
                {
                    values.Add(enumerationFacet.Value);
                }
                else
                {
                    return false;
                }
            }

            return values.Count > 0;
        }

        private string ResolveEnumName(XmlSchemaSimpleType simpleType, string fallbackName)
        {
            var name = simpleType.Name ?? fallbackName;
            var enumName = ToPascal(name);
            if (!enumName.EndsWith("Enum", StringComparison.OrdinalIgnoreCase))
            {
                enumName += "Enum";
            }

            return enumName;
        }

        private void RegisterEnum(string enumName, List<string> values)
        {
            if (_enumNames.ContainsKey(enumName))
            {
                return;
            }

            var members = BuildEnumMembers(values);
            var generatedEnum = new GeneratedEnum(enumName, members);
            _enumNames[enumName] = generatedEnum;
            _enums.Add(generatedEnum);
        }

        private List<EnumMember> BuildEnumMembers(IEnumerable<string> values)
        {
            var usedNames = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
            var members = new List<EnumMember>();

            foreach (var value in values)
            {
                var normalized = NormalizeEnumMember(value);
                if (string.IsNullOrWhiteSpace(normalized))
                {
                    normalized = "Unknown";
                }

                if (usedNames.TryGetValue(normalized, out var count))
                {
                    count += 1;
                    usedNames[normalized] = count;
                    normalized = $"{normalized}{count}";
                }
                else
                {
                    usedNames[normalized] = 1;
                }

                members.Add(new EnumMember(normalized, value));
            }

            return members;
        }

        private string NormalizeEnumMember(string value)
        {
            var trimmed = value?.Trim();
            if (string.IsNullOrWhiteSpace(trimmed))
            {
                return "Unknown";
            }

            if (TryGetEnumOverride(trimmed ?? string.Empty, out var overrideName))
            {
                return overrideName;
            }

            var cleaned = new string(trimmed.Where(ch => char.IsLetterOrDigit(ch) || ch == '_' || ch == '-' || ch == ' ').ToArray());
            if (string.IsNullOrWhiteSpace(cleaned))
            {
                return "Unknown";
            }

            var tokens = cleaned
                .Split(new[] { '-', '_', ' ' }, StringSplitOptions.RemoveEmptyEntries)
                .Select(NormalizeToken)
                .Where(token => !string.IsNullOrWhiteSpace(token))
                .ToList();

            var candidate = string.Concat(tokens);
            if (string.IsNullOrWhiteSpace(candidate))
            {
                return "Unknown";
            }

            if (char.IsDigit(candidate[0]))
            {
                return $"Value{candidate}";
            }

            return candidate;
        }

        private bool TryGetEnumOverride(string value, out string name)
        {
            var map = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
            {
                ["fanart"] = "FanArt",
                ["clearlogo"] = "ClearLogo",
                ["clearart"] = "ClearArt",
                ["discart"] = "DiscArt",
                ["characterart"] = "CharacterArt",
                ["keyart"] = "KeyArt",
                ["non-binary"] = "NonBinary",
                ["in production"] = "InProduction"
            };

            return map.TryGetValue(value, out name!);
        }

        private string NormalizeToken(string token)
        {
            var acronyms = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
            {
                "tv",
                "id",
                "url",
                "api",
                "imdb",
                "tmdb",
                "tvdb",
                "mpaa",
                "bbfc",
                "fsk",
                "esrb"
            };

            if (acronyms.Contains(token))
            {
                return token.ToUpperInvariant();
            }

            return ToPascal(token);
        }

        private string ToPascal(string value)
        {
            if (string.IsNullOrWhiteSpace(value))
            {
                return "Value";
            }

            var parts = value.Split(new[] { '-', '_', ' ' }, StringSplitOptions.RemoveEmptyEntries);
            var builder = new StringBuilder();
            foreach (var part in parts)
            {
                if (part.Length == 0)
                {
                    continue;
                }

                builder.Append(char.ToUpperInvariant(part[0]));
                if (part.Length > 1)
                {
                    builder.Append(part.Substring(1));
                }
            }

            return builder.ToString();
        }
    }

    private sealed class GeneratedType
    {
        public GeneratedType(string name, string? schemaName, bool isRoot = false)
        {
            Name = name;
            SchemaName = schemaName;
            IsRoot = isRoot;
        }

        public string Name { get; }
        public string? SchemaName { get; }
        public bool IsRoot { get; }
        public List<PropertySpec> Properties { get; } = new();
        public List<GeneratedType> NestedTypes { get; } = new();

        public string ToCode()
        {
            var builder = new StringBuilder();
            if (IsRoot)
            {
                builder.AppendLine("[XmlRoot(\"root\", Namespace = NfoConstants.Namespace)]");
            }
            else
            {
                if (!string.IsNullOrWhiteSpace(SchemaName) && !string.Equals(Name, SchemaName, StringComparison.OrdinalIgnoreCase))
                {
                    builder.AppendLine($"[XmlType(\"{SchemaName}\", Namespace = NfoConstants.Namespace)]");
                }
                else
                {
                    builder.AppendLine("[XmlType(Namespace = NfoConstants.Namespace)]");
                }
            }

            builder.AppendLine($"public sealed partial class {Name}");
            builder.AppendLine("{");
            foreach (var property in Properties)
            {
                builder.AppendLine(property.ToCode());
            }
            builder.AppendLine("}");

            return builder.ToString();
        }
    }

    private sealed class PropertySpec
    {
        public PropertySpec(string name, string typeName, string attribute, string? xmlName = null, bool isList = false, string? dataType = null, bool ignore = false)
        {
            Name = name;
            TypeName = typeName;
            Attribute = attribute;
            XmlName = xmlName;
            IsList = isList;
            DataType = dataType;
            Ignore = ignore;
        }

        public string Name { get; }
        public string TypeName { get; }
        public string Attribute { get; }
        public string? XmlName { get; }
        public bool IsList { get; }
        public bool Ignore { get; }
        public string? DataType { get; }

        public static PropertySpec XmlIgnore(string name, string typeName)
        {
            return new PropertySpec(name, typeName, "XmlIgnore", null, false, null, true);
        }

        public string ToCode()
        {
            var builder = new StringBuilder();
            var attribute = Ignore
                ? "XmlIgnore"
                : BuildAttribute();
            builder.AppendLine($"    [{attribute}]");
            var propertyType = IsList ? $"List<{TypeName.TrimEnd('?')}>" : TypeName;
            var initializer = IsList ? " = new();" : string.Empty;
            builder.AppendLine($"    public {propertyType} {Name} {{ get; set; }}{initializer}");
            builder.AppendLine();
            return builder.ToString();
        }

        private string BuildAttribute()
        {
            var namePart = XmlName == null ? string.Empty : $"\"{XmlName}\"";
            if (string.IsNullOrWhiteSpace(DataType))
            {
                return XmlName == null ? Attribute : $"{Attribute}({namePart})";
            }

            var dataTypePart = $"DataType=\"{DataType}\"";
            if (XmlName == null)
            {
                return $"{Attribute}({dataTypePart})";
            }

            return $"{Attribute}({namePart}, {dataTypePart})";
        }
    }

    private sealed class GeneratedEnum
    {
        public GeneratedEnum(string name, List<EnumMember> members)
        {
            Name = name;
            Members = members;
        }

        public string Name { get; }
        public List<EnumMember> Members { get; }

        public string ToCode()
        {
            var builder = new StringBuilder();
            builder.AppendLine($"public enum {Name}");
            builder.AppendLine("{");
            foreach (var member in Members)
            {
                var xmlValue = member.XmlValue.Replace("\"", "\\\"");
                builder.AppendLine($"    [XmlEnum(\"{xmlValue}\")]");
                builder.AppendLine($"    {member.Name},");
            }
            builder.AppendLine("}");
            builder.AppendLine();
            return builder.ToString();
        }
    }

    private sealed class EnumMember
    {
        public EnumMember(string name, string xmlValue)
        {
            Name = name;
            XmlValue = xmlValue;
        }

        public string Name { get; }
        public string XmlValue { get; }
    }
}
